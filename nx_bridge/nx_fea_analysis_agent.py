"""
Siemens NX bridge (Pillar 4)
  * create_3d_prt   - runs the app-exported NX Open journal with run_journal.exe, UNMODIFIED in
                      geometry (only the headless "open/save part" wrapper is added), then opens NX.
  * run_fea_solve   - genuine finite-element gravity analysis of the exact journal geometry:
                      NX Nastran SOL 101 when nastran.exe is installed, otherwise CalculiX.
                      (The previous version returned a closed-form formula labelled "NASTRAN".)
"""

import os
import sys
import json
import time
import math
import glob
import subprocess

# Ensure workspace root is in sys.path
workspace_root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if workspace_root not in sys.path:
    sys.path.insert(0, workspace_root)

from optimizer.node_snapping import snap_18_whiffletree_hubs


class NXFEAAnalysisEngine:
    def __init__(self, custom_nx_bin=None):
        self.nx_bin_dir = self._detect_nx_bin(custom_nx_bin)
        self.run_journal_exe = os.path.join(self.nx_bin_dir, "run_journal.exe") if self.nx_bin_dir else None

    def _detect_nx_bin(self, custom_dir=None):
        """Automatically discovers Siemens NX NXBIN path on Windows."""
        if custom_dir and os.path.exists(os.path.join(custom_dir, "run_journal.exe")):
            return custom_dir

        candidate_dirs = [
            r"C:\Program Files\Siemens\NX2007\NXBIN",
            r"C:\Program Files\Siemens\NX\NXBIN",
            r"C:\Program Files\Siemens\NX2206\NXBIN",
            r"C:\Program Files\Siemens\NX2212\NXBIN",
            r"C:\Program Files\Siemens\NX2306\NXBIN",
            r"C:\Program Files\Siemens\NX2312\NXBIN",
            r"C:\Program Files\Siemens\NX2406\NXBIN",
        ]

        # Also search for any NX* directory under Program Files\Siemens
        glob_dirs = glob.glob(r"C:\Program Files\Siemens\NX*\NXBIN")
        all_candidates = candidate_dirs + glob_dirs

        for d in all_candidates:
            if os.path.exists(os.path.join(d, "run_journal.exe")):
                return d
        return None

    def is_nx_installed(self):
        return self.run_journal_exe is not None and os.path.exists(self.run_journal_exe)

    def generate_nx_journal_script(self, *args, **kwargs):
        """The only valid journal is the one generated by the app (app.js generateNXCode), so the
        NX part always has the same design the app shows.  The old fallback here built a different
        design (circular pockets) and has been removed."""
        raise RuntimeError("Export the journal from the app (Generate NX Code) and pass it as journal_code.")

    def create_3d_prt(self, D=560.0, Dc=120.0, H=73.7, tf=1.0, tw=3.0, L=55.5, rf=3.0, target_prt="primary_mirror_560mm.prt", journal_code=None):
        """
        1-Click Automated Siemens NX Connection:
        1. Compiles the exact textbook isogrid Python journal from UI (or fallback generator).
        2. Pre-builds the exact .PRT part via run_journal.exe with full adaptive pocketing and revolve blank.
        3. Automatically launches Siemens NX CAM GUI with -nxcam -retrieve:"<prt>" onto user's desktop.
        """
        abs_prt = os.path.abspath(target_prt)
        abs_journal = os.path.abspath(os.path.join(os.path.dirname(__file__), "build_mirror_journal.py"))
        ugraf_exe = os.path.join(self.nx_bin_dir, "ugraf.exe") if self.nx_bin_dir else None

        # 1. Use the exact exported journal from the UI if provided
        abs_prt_fwd = abs_prt.replace('\\', '/')
        if journal_code and len(journal_code.strip()) > 50:
            patched_code = journal_code
            new_workpart_check = f'''    workPart = session.Parts.Work
    if workPart is None:
        prt_path = r"{abs_prt_fwd}"
        try:
            import os
            if os.path.exists(prt_path):
                os.remove(prt_path)
        except Exception:
            pass
        workPart = session.Parts.NewDisplay(prt_path, NXOpen.Part.Units.Millimeters)'''

            old_workpart_check = '''    workPart = session.Parts.Work
    if workPart is None:
        log(lw, "ERROR: No active part open. Go to File -> New -> Model (mm).")
        return'''

            if old_workpart_check in patched_code:
                patched_code = patched_code.replace(old_workpart_check, new_workpart_check)
            elif 'workPart = session.Parts.Work' in patched_code:
                import re
                patched_code = re.sub(r'workPart\s*=\s*session\.Parts\.Work\s*[\r\n]+(?:\s*if\s*workPart\s*is\s*None:[\s\S]*?return)?', new_workpart_check.strip(), patched_code)

            save_block = f'''    try:
        if workPart is not None:
            workPart.Save(NXOpen.BasePart.SaveComponents.TrueValue, NXOpen.BasePart.CloseAfterSave.FalseValue)
            print(f"[NX Open SUCCESS] Model saved to: {abs_prt_fwd}")
    except Exception as e_save:
        print(f"[NX Open] Save warning: {{e_save}}")

if __name__ == '__main__':'''
            if "if __name__ == '__main__':" in patched_code:
                patched_code = patched_code.replace("if __name__ == '__main__':", save_block)
            else:
                patched_code += '\n' + save_block

            # NOTE: pocket geometry is never modified here (the old "sanitize" patch that rewrote
            # pocket bounds / corner segments changed the design that NX built).
            with open(abs_journal, 'w', encoding='utf-8') as f:
                f.write(patched_code)
            print(f"[Pillar 4 NX Bridge] Loaded exact UI exported journal ({len(patched_code)} bytes).")
        else:
            return {
                "status": "NO_JOURNAL",
                "message": "No journal received from the app. Use the app's Create 3D Part button so the exact design is built.",
                "nx_installed": self.is_nx_installed()
            }

        if not self.is_nx_installed():
            return {
                "status": "JOURNAL_GENERATED",
                "message": "Siemens NX executable not found on default path. Journal script generated for direct execution.",
                "journal_path": abs_journal,
                "target_prt": abs_prt,
                "nx_installed": False
            }

        # 2. Terminate any previous ugraf.exe session first so Siemens NX releases any file lock on .PRT
        try:
            cleanup_cmd = "Stop-ScheduledTask -TaskName 'Launch_NX_CAM' -ErrorAction SilentlyContinue; Stop-Process -Name ugraf -Force -ErrorAction SilentlyContinue"
            subprocess.run(["powershell.exe", "-NoProfile", "-NonInteractive", "-Command", cleanup_cmd], capture_output=True, timeout=8)
            import time
            time.sleep(1)
        except Exception as e_clean:
            print(f"[Pillar 4 NX Bridge] Stale ugraf cleanup note: {e_clean}")

        # 3. Execute run_journal.exe to build the exact native 3D .PRT
        print(f"[Pillar 4 NX Bridge] Pre-building exact native .PRT via run_journal.exe...")
        try:
            cmd_headless = [self.run_journal_exe, abs_journal]
            res_build = subprocess.run(cmd_headless, capture_output=True, text=True, timeout=360)
            if res_build.returncode == 0:
                print(f"[Pillar 4 NX Bridge] Headless journal execution SUCCESS.")
            else:
                print(f"[Pillar 4 NX Bridge] Headless run_journal output: {res_build.stdout[-500:] if res_build.stdout else ''} {res_build.stderr[-500:] if res_build.stderr else ''}")
        except Exception as e:
            print(f"[Pillar 4 NX Bridge] Headless pre-build note: {e}")

        # Check that part file was successfully generated before launching GUI
        if not os.path.exists(abs_prt):
            return {
                "status": "BUILD_FAILED",
                "message": f"Siemens NX headless journal compilation did not finish. Part file '{target_prt}' was not created.",
                "journal_path": abs_journal,
                "target_prt": abs_prt,
                "nx_installed": True
            }

        # 4. Automatically launch Siemens NX GUI and open the generated 3D part model
        if ugraf_exe and os.path.exists(ugraf_exe):
            nxcam_dir = r"C:\Program Files\Siemens\NX2007\MACH\auxiliary\nxcam"
            work_dir = nxcam_dir if os.path.exists(nxcam_dir) else workspace_root
            env = os.environ.copy()
            env["SPLM_LICENSE_SERVER"] = "27800@localhost"
            env["UGII_BASE_DIR"] = r"C:\Program Files\Siemens\NX2007"
            env["UGII_ROOT_DIR"] = r"C:\Program Files\Siemens\NX2007\NXBIN"

            nxcam_args = f'-nxcam -retrieve:"{abs_prt}"'
            print(f"[Pillar 4 NX Bridge] Opening Siemens NX CAM with CAD model: {ugraf_exe} {nxcam_args}")
            launched = False

            # Strategy 1: Windows Interactive Task Scheduler (Bypasses service/background desktop isolation, guarantees window on WinSta0\default)
            try:
                ps_cmd = f'''
                $action = New-ScheduledTaskAction -Execute "{ugraf_exe}" -Argument '-nxcam -retrieve:"{abs_prt}"' -WorkingDirectory "{work_dir}"
                $settings = New-ScheduledTaskSettingsSet -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries -MultipleInstances IgnoreNew
                Register-ScheduledTask -TaskName "Launch_NX_CAM" -Action $action -Settings $settings -Force | Out-Null
                Start-ScheduledTask -TaskName "Launch_NX_CAM"
                '''
                res = subprocess.run(["powershell.exe", "-NoProfile", "-NonInteractive", "-Command", ps_cmd], capture_output=True, text=True, timeout=12)
                if res.returncode == 0:
                    launched = True
                    print("[Pillar 4 NX Bridge] NX CAM launched successfully via Interactive Task Scheduler onto desktop.")
            except Exception as e_task:
                print(f"[Pillar 4 NX Bridge] Task Scheduler error: {e_task}")

            # Strategy 2: Windows Shell COM (delegates launch to desktop Explorer in user's interactive session)
            if not launched:
                try:
                    import win32com.client
                    shell_app = win32com.client.Dispatch("Shell.Application")
                    shell_app.ShellExecute(ugraf_exe, nxcam_args, work_dir, "open", 1)
                    launched = True
                    print("[Pillar 4 NX Bridge] NX CAM dispatched via Shell.Application COM successfully.")
                except Exception as e_com:
                    print(f"[Pillar 4 NX Bridge] Shell.Application COM note: {e_com}")

            # Strategy 3: Win32 ShellExecuteW API
            if not launched:
                try:
                    import ctypes
                    res = ctypes.windll.shell32.ShellExecuteW(None, "open", ugraf_exe, nxcam_args, work_dir, 1)
                    if res > 32:
                        launched = True
                        print("[Pillar 4 NX Bridge] NX CAM dispatched via ShellExecuteW successfully.")
                except Exception as e_sh:
                    print(f"[Pillar 4 NX Bridge] ShellExecuteW error: {e_sh}")

            # Strategy 4: Detached Subprocess Popen
            if not launched:
                try:
                    creation_flags = 0
                    if hasattr(subprocess, "DETACHED_PROCESS"):
                        creation_flags |= subprocess.DETACHED_PROCESS
                    if hasattr(subprocess, "CREATE_NEW_PROCESS_GROUP"):
                        creation_flags |= subprocess.CREATE_NEW_PROCESS_GROUP
                    subprocess.Popen([ugraf_exe, "-nxcam", f'-retrieve:{abs_prt}'], cwd=work_dir, env=env, creationflags=creation_flags)
                    launched = True
                    print("[Pillar 4 NX Bridge] NX CAM dispatched via detached subprocess.Popen.")
                except Exception as e_pop:
                    print(f"[Pillar 4 NX Bridge] Subprocess Popen error: {e_pop}")

            return {
                "status": "NX_LAUNCHED",
                "message": "NX Manufacturing - NX CAM opened automatically! 3D mirror CAD model loaded on screen.",
                "journal_path": abs_journal,
                "target_prt": abs_prt,
                "nx_installed": True
            }

        prt_exists = os.path.exists(abs_prt)
        return {
            "status": "PRT_GENERATED" if prt_exists else "JOURNAL_READY",
            "message": "Native Siemens NX .PRT model generated successfully!" if prt_exists else "NX Open journal generated and execution dispatched.",
            "journal_path": abs_journal,
            "target_prt": abs_prt,
            "prt_created": prt_exists,
            "nx_installed": True
        }

    def run_fea_solve(self, D=560.0, Dc=175.0, H=73.7, tf=1.0, tw=3.0, L=55.5, rf=3.0,
                      material="zerodur", mesh_size=8.0, solver_backend="auto"):
        """
        Genuine linear-static FEA (1 g along the optical axis, 18 Hindle pads) of the exact
        isogrid geometry the journal builds.  Uses NX Nastran (SOL 101) if installed, else CalculiX.
        Returns optical surface RMS/PV (piston+tilt removed), power-removed RMS and 37 Zernikes.
        """
        from fea_engine.mirror_fea import run_gravity_fea_params
        res = run_gravity_fea_params(D, Dc, H, tf, tw, L, rf, material=material,
                                     mesh_size=mesh_size, solver_backend=solver_backend)
        hubs = snap_18_whiffletree_hubs(D, L, Dc)
        return {
            "solver": res["solver"],
            "status": "CONVERGED",
            "solve_duration_sec": round(res["time_mesh_s"] + res["time_solve_s"], 1),
            "actual_mass_kg": round(res["replica_mass_kg"], 4),
            "fe_model_mass_kg": round(res["occ_mass_kg"], 4),
            "actual_rms_sag_nm": round(res["rms_sag_nm"], 3),
            "actual_pv_sag_nm": round(res["pv_sag_nm"], 3),
            "actual_rms_sag_power_removed_nm": round(res["rms_sag_power_removed_nm"], 3),
            "zernike_fringe_37_nm": res["zernike_fringe_37_nm"],
            "mesh": {"size_mm": res["mesh_size_mm"], "nodes": res["n_nodes"], "elements": res["n_elements"]},
            "reaction_check": {"support_reaction_N": res["reaction_z_wedge_N"], "weight_N": res["weight_wedge_N"]},
            "whiffletree_hubs_count": len(hubs),
            "raw": {k: v for k, v in res.items() if k != "zernike_fringe_37_nm"},
        }
